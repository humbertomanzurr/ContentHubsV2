const LANGS = { es: ES, en: null };
let LANG = (()=>{ try{ return localStorage.getItem("ch_lang")||"es"; }catch(e){ return "es"; } })();

const getLang = () => LANG;
const setLang = (l) => {
  LANG = (l==="en"||l==="es") ? l : "es";
  try{ localStorage.setItem("ch_lang", LANG); }catch(e){}
  // Simplest correct approach: re-render everything from the root.
  window.location.reload();
};
const t = (s) => {
  const dict = LANGS[LANG];
  return (dict && dict[s]) ? dict[s] : s;
};

export { t, getLang, setLang };
